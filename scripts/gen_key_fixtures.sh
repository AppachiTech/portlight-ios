#!/usr/bin/env bash
# Regenerates Tests/PortlightKitTests/KeyFixtures.swift from real ssh-keygen
# and openssl output. These keys are throwaway test data, never used anywhere.
set -euo pipefail
cd "$(dirname "$0")/.."
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
pass="correct horse battery staple"

gen() { # name, ssh-keygen args...
  local name=$1; shift
  ssh-keygen -q -C "portlight-test-$name" -f "$tmp/$name" "$@" </dev/null >/dev/null
}
gen ed25519_plain -t ed25519 -N ""
gen ed25519_enc -t ed25519 -N "$pass" -a 4
gen ed25519_enc16 -t ed25519 -N "$pass"
gen p256_plain -t ecdsa -b 256 -N ""
gen p384_enc -t ecdsa -b 384 -N "$pass" -a 4
gen p521_enc -t ecdsa -b 521 -N "$pass" -a 4
gen ed25519_aes128ctr -t ed25519 -N "$pass" -a 4 -Z aes128-ctr
gen ed25519_aes256cbc -t ed25519 -N "$pass" -a 4 -Z aes256-cbc
gen ed25519_gcm -t ed25519 -N "$pass" -a 4 -Z aes256-gcm@openssh.com
gen rsa_plain -t rsa -b 2048 -N ""
gen p256_pem -t ecdsa -b 256 -N "" -m PEM
openssl genpkey -algorithm ed25519 -out "$tmp/ed25519_pkcs8" 2>/dev/null
openssl genpkey -algorithm EC -pkeyopt ec_paramgen_curve:P-384 -out "$tmp/p384_pkcs8" 2>/dev/null
openssl genpkey -algorithm RSA -pkeyopt rsa_keygen_bits:2048 -out "$tmp/rsa_pkcs8" 2>/dev/null
ssh-keygen -y -f "$tmp/p384_pkcs8" > "$tmp/p384_pkcs8.pub"
# ssh-keygen can't read Ed25519 PKCS#8, so build its public line from the raw key.
openssl pkey -in "$tmp/ed25519_pkcs8" -pubout -outform DER 2>/dev/null | tail -c 32 > "$tmp/ed25519_raw"
python3 - "$tmp/ed25519_raw" > "$tmp/ed25519_pkcs8.pub" <<'PY'
import base64, struct, sys
raw = open(sys.argv[1], "rb").read()
s = lambda b: struct.pack(">I", len(b)) + b
print("ssh-ed25519 " + base64.b64encode(s(b"ssh-ed25519") + s(raw)).decode())
PY

out=Tests/PortlightKitTests/KeyFixtures.swift
{
  echo "// Generated by scripts/gen_key_fixtures.sh from ssh-keygen and openssl."
  echo "// Throwaway keys for tests only."
  echo ""
  echo "enum KeyFixtures {"
  echo "    static let passphrase = \"$pass\""
  for f in ed25519_plain ed25519_enc ed25519_enc16 p256_plain p384_enc p521_enc ed25519_aes128ctr ed25519_aes256cbc ed25519_gcm rsa_plain p256_pem ed25519_pkcs8 p384_pkcs8 rsa_pkcs8; do
    name=$(echo "$f" | sed -E 's/_([a-z0-9])/\U\1/g')
    echo ""
    echo "    static let $name = \"\"\""
    sed "s/^/    /" "$tmp/$f"
    echo "    \"\"\""
    if [ -f "$tmp/$f.pub" ]; then
      echo "    static let ${name}Public = \"$(cut -d' ' -f1-2 "$tmp/$f.pub")\""
      echo "    static let ${name}Fingerprint = \"$(ssh-keygen -lf "$tmp/$f.pub" | awk '{print $2}')\""
    fi
  done
  echo "}"
} > "$out"
echo "wrote $out"
